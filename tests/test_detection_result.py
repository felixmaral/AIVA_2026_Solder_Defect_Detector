"""
tests/test_detection_result.py — Unit tests for the DetectionResult aggregator.

Verifies that defects are correctly accumulated into the result registry and
that the XML manifest generated by ``to_xml`` is well-formed and complete.
"""
import unittest
from src.core.solder_defect import SolderDefect
from src.core.detection_result import DetectionResult


class TestDetectionResult(unittest.TestCase):
    """
    Test suite for the ``DetectionResult`` defect aggregator and XML serialiser.
    """

    def test_add_and_batch_xml(self):
        """
        Verifies that multiple defects are accumulated and serialised correctly.

        Adds two ``SolderDefect`` instances with distinct coordinates and checks:
        - The registry length equals the number of added defects.
        - The XML manifest contains the correct ``<detection_count>`` summary.
        - Bounding box coordinates from both defects appear in the output XML.
        - The XML document is properly closed with ``</result>``.
        """
        result = DetectionResult()
        defect1 = SolderDefect(10, 20, 50, 60, 0.88)
        defect2 = SolderDefect(100, 200, 500, 600, 0.99)

        result.add_defect(defect1)
        result.add_defect(defect2)

        xml = result.to_xml()

        self.assertEqual(len(result.defects), 2)
        self.assertIn("<detection_count>2</detection_count>", xml)
        # Verify that coordinates from both defects appear in the output
        self.assertIn("<x>10</x>", xml)
        self.assertIn("<y>200</y>", xml)
        # Verify the root element is properly closed
        self.assertIn("</result>", xml)


if __name__ == '__main__':
    unittest.main()
